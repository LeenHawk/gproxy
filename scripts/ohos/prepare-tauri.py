#!/usr/bin/env python3
"""Apply the pinned experimental dependency overlay in an OHOS build checkout only."""
import json
import os
from pathlib import Path
import re
import subprocess
import tomllib

root = Path.cwd()
source = Path(os.environ["OHOS_TAURI_SOURCES"]).resolve()
pins = json.loads((root / "scripts/ohos/tauri-pins.json").read_text())
for name, pin in pins.items():
    checkout = source / name
    if not (checkout / ".git").is_dir():
        subprocess.run(["git", "init", str(checkout)], check=True)
        subprocess.run(["git", "-C", str(checkout), "remote", "add", "origin",
                        f"https://github.com/{pin['repository']}.git"], check=True)
    subprocess.run(["git", "-C", str(checkout), "fetch", "--depth", "1", "origin", pin["revision"]], check=True)
    subprocess.run(["git", "-C", str(checkout), "checkout", "--detach", "FETCH_HEAD"], check=True)

patches = {}
for manifest in (source / "tauri/crates").glob("*/Cargo.toml"):
    name = tomllib.loads(manifest.read_text()).get("package", {}).get("name", "")
    if name.startswith("tauri"):
        patches[name] = manifest.parent
for name in ("wry", "tao", "cargo-mobile2"):
    patches[name] = source / name
ability = source / "ability"
# Pin the matching Ability revision in all experimental upstream manifests too.
for checkout in (source / "tauri", source / "wry", source / "tao"):
    for manifest in checkout.rglob("Cargo.toml"):
        text = manifest.read_text()
        text = text.replace('git = "https://github.com/harmony-contrib/openharmony-ability.git"',
                            'git = "https://github.com/harmony-contrib/openharmony-ability.git", rev = "' + pins["ability"]["revision"] + '"')
        manifest.write_text(text)

manifest = root / "Cargo.toml"
text = manifest.read_text()
for name in ("tauri", "tauri-build"):
    text = re.sub(rf'^{name} = .*$', f'{name} = {{ path = "{patches[name]}" }}', text, count=1, flags=re.MULTILINE)
# Desktop plugins have a newer Tauri minimum, but are not part of an OHOS app.
host = root / "crates/gproxy-host-tauri/Cargo.toml"
host_text = host.read_text()
for name in ("tauri-plugin-dialog", "tauri-plugin-single-instance"):
    host_text = re.sub(rf'^{name} = .*\n', '', host_text, flags=re.MULTILINE)
host.write_text(host_text + '\n[target.\'cfg(target_env = "ohos")\'.dependencies]\nnapi-ohos = "=1.2.0"\nnapi-derive-ohos = "=1.2.0"\n')
text += '\n# Experimental OpenHarmony build overlay; generated by scripts/ohos/prepare-tauri.py.\n'
for name, path in patches.items():
    text += f'{name} = {{ path = "{path}" }}\n'
manifest.write_text(text)
# The CLI's own workspace needs the same pinned Wry/Tao/mobile code.
upstream = source / "tauri/Cargo.toml"
text = upstream.read_text()
for name in ("wry", "tao", "cargo-mobile2"):
    text = re.sub(rf'^{name} = .*$', f'{name} = {{ path = "{patches[name]}" }}', text, flags=re.MULTILINE)
upstream.write_text(text)
print(f"Prepared OHOS-only Tauri overlay at {source}")
# The upstream helper assumes an API-level directory below openharmony. Huawei's
# command-line SDK has native directly below openharmony; respect its explicit root.
env_file = source / "cargo-mobile2/src/open_harmony/env.rs"
text = env_file.read_text()
old = '''self.ohos_home
                .parent()
                .unwrap()
                .parent()
                .unwrap()
                .parent()
                .unwrap()
                .as_os_str()
                .to_os_string()'''
new = '''std::env::var_os("DEVECO_SDK_HOME").expect("DEVECO_SDK_HOME is required")'''
if old not in text:
    raise ValueError("Upstream OpenHarmony SDK layout helper changed")
env_file.write_text(text.replace(old, new))
